"""Strict independent Full HD smoke gate for real Studio MP4 exports.

The input is a *synthetic sine-wave engineering fixture* generated by
scripts/smoke_export.py. It cannot approve Vietnamese voice, scientific
accuracy, real model output, motion quality or a release.
"""

from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import math
import re
import subprocess
from fractions import Fraction
from pathlib import Path
from typing import Any

ASPECTS = {
    "portrait": (1080, 1920),
    "landscape": (1920, 1080),
}


class IntegrityError(ValueError):
    """A mandatory, independently checked export invariant failed."""


def command(args: list[str], timeout: int = 180) -> str:
    result = subprocess.run(
        args, capture_output=True, text=True, timeout=timeout, check=False
    )
    if result.returncode:
        raise IntegrityError(
            f"Command exited {result.returncode}: {args[0]}: {result.stderr[-1500:]}"
        )
    return result.stdout


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def locate_mp4s(root: Path) -> dict[str, Path]:
    paths = {}
    for aspect in ASPECTS:
        folder = root / aspect / "exports"
        matches = sorted(folder.glob("*.mp4")) if folder.is_dir() else []
        if (
            len(matches) != 1
            or not matches[0].is_file()
            or matches[0].stat().st_size <= 0
        ):
            raise IntegrityError(
                f"{aspect}: expected exactly one nonempty MP4 in {folder}, got {len(matches)}"
            )
        paths[aspect] = matches[0]
    if paths["portrait"].resolve() == paths["landscape"].resolve():
        raise IntegrityError("Both aspect exports resolve to the same file")
    return paths


def validate_streams(
    info: dict[str, Any], aspect: str, seconds: float
) -> dict[str, Any]:
    if aspect not in ASPECTS:
        raise IntegrityError(f"Unsupported aspect: {aspect}")
    streams = info.get("streams") or []
    videos = [s for s in streams if s.get("codec_type") == "video"]
    audios = [s for s in streams if s.get("codec_type") == "audio"]
    if len(videos) != 1 or len(audios) != 1 or len(streams) != 2:
        raise IntegrityError(f"{aspect}: expected exactly one video + one audio stream")
    video, audio = videos[0], audios[0]
    if (video.get("width"), video.get("height")) != ASPECTS[aspect]:
        raise IntegrityError(f"{aspect}: wrong export dimensions")
    if video.get("codec_name") != "h264" or video.get("pix_fmt") != "yuv420p":
        raise IntegrityError(f"{aspect}: expected H.264 yuv420p")
    for rate in ("r_frame_rate", "avg_frame_rate"):
        try:
            if Fraction(video.get(rate, "0/1")) != 30:
                raise IntegrityError(f"{aspect}: {rate} is not 30 fps")
        except (ValueError, ZeroDivisionError):
            raise IntegrityError(f"{aspect}: malformed frame rate {rate}") from None
    if audio.get("codec_name") != "aac" or str(audio.get("sample_rate")) != "48000":
        raise IntegrityError(f"{aspect}: expected AAC 48000 Hz")
    durations = {}
    for label, obj in [
        ("video", video),
        ("audio", audio),
        ("container", info.get("format") or {}),
    ]:
        try:
            duration = float(obj["duration"])
        except (ValueError, TypeError, KeyError):
            raise IntegrityError(f"{aspect}: missing {label} duration") from None
        if not math.isfinite(duration) or abs(duration - seconds) > 0.12:
            raise IntegrityError(f"{aspect}: wrong {label} duration {duration}")
        durations[label] = duration
    if abs(durations["audio"] - durations["video"]) > 0.12:
        raise IntegrityError(f"{aspect}: A/V duration drift")
    return {
        "dimensions": list(ASPECTS[aspect]),
        "video_codec": "h264",
        "pix_fmt": "yuv420p",
        "fps": 30,
        "audio_codec": "aac",
        "audio_hz": 48000,
        "duration_seconds": durations,
    }


def validate_frame_pts(frames: list[dict[str, Any]], seconds: float) -> dict[str, Any]:
    expected = round(seconds * 30)
    if len(frames) != expected:
        raise IntegrityError(
            f"Wrong decoded frame count: {len(frames)} versus {expected}"
        )
    pts = []
    for frame in frames:
        try:
            value = float(frame["best_effort_timestamp_time"])
        except (ValueError, TypeError, KeyError):
            raise IntegrityError("Frame has no valid PTS") from None
        if not math.isfinite(value):
            raise IntegrityError("Nonfinite frame PTS")
        pts.append(value)
    if abs(pts[0]) > 0.001:
        raise IntegrityError(f"Frame PTS does not begin at zero: {pts[0]}")
    jumps = [b - a for a, b in itertools.pairwise(pts)]
    if any(abs(jump - (1 / 30)) > 0.001 for jump in jumps):
        raise IntegrityError("Non-CFR, repeated or missing frame timestamps")
    if abs(pts[-1] - (expected - 1) / 30) > 0.001:
        raise IntegrityError("Frame PTS ends at unexpected time")
    return {"decoded_frames": len(pts), "first_pts": pts[0], "last_pts": pts[-1]}


def parse_loudnorm_log(log: str) -> dict[str, float]:
    # loudnorm prints measured input loudness/true peak on the final stderr JSON.
    found = re.search(
        r'\{\s*"input_i"\s*:\s*"([^"]+)"\s*,\s*"input_tp"\s*:\s*"([^"]+)"',
        log,
    )
    if not found:
        raise IntegrityError("FFmpeg loudnorm measurements missing")
    try:
        integrated, true_peak = (float(value) for value in found.groups())
    except ValueError:
        raise IntegrityError("Unparseable loudness") from None
    if not math.isfinite(integrated) or not math.isfinite(true_peak):
        raise IntegrityError("Nonfinite loudness/true peak")
    if not -17 <= integrated <= -15:
        raise IntegrityError(f"Loudness {integrated} LUFS is outside -16 ±1 LUFS")
    if true_peak > -1:
        raise IntegrityError(f"True peak {true_peak} dBTP exceeds -1 dBTP")
    return {"integrated_lufs": integrated, "true_peak_dbtp": true_peak}


def verify_video(path: Path, aspect: str, seconds: float) -> dict[str, Any]:
    info = json.loads(
        command(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_entries",
                (
                    "format=duration:stream=codec_type,codec_name,width,height,pix_fmt,"
                    "r_frame_rate,avg_frame_rate,sample_rate,duration"
                ),
                "-of",
                "json",
                str(path),
            ]
        )
    )
    streams = validate_streams(info, aspect, seconds)
    frames = json.loads(
        command(
            [
                "ffprobe",
                "-v",
                "error",
                "-select_streams",
                "v:0",
                "-show_frames",
                "-show_entries",
                "frame=best_effort_timestamp_time",
                "-of",
                "json",
                str(path),
            ]
        )
    ).get("frames", [])
    pts = validate_frame_pts(frames, seconds)
    command(
        [
            "ffmpeg",
            "-hide_banner",
            "-v",
            "error",
            "-xerror",
            "-i",
            str(path),
            "-map",
            "0",
            "-f",
            "null",
            "-",
        ]
    )
    loudness = subprocess.run(
        [
            "ffmpeg",
            "-hide_banner",
            "-nostats",
            "-i",
            str(path),
            "-vn",
            "-af",
            "loudnorm=I=-16:TP=-1:LRA=11:print_format=json",
            "-f",
            "null",
            "-",
        ],
        capture_output=True,
        text=True,
        timeout=180,
        check=False,
    )
    if loudness.returncode:
        raise IntegrityError("FFmpeg could not measure final audio loudness")
    measured = parse_loudnorm_log(loudness.stderr)
    return {
        "filename": path.name,
        "sha256": sha256_file(path),
        "bytes": path.stat().st_size,
        "streams": streams,
        "frames": pts,
        "audio": measured,
        "full_decode": "passed",
        "technical": "passed",
        "human_review": "not_run",
    }


def run(root: Path, output: Path, seconds: float) -> int:
    report: dict[str, Any] = {
        "fixture": "Pillow-generated diagrams + synthetic sine tone; NOT Vietnamese narration",
        "release_approved": False,
        "human_review": "not_run",
        "verified_aspects": {},
        "errors": {},
    }
    try:
        paths = locate_mp4s(root)
        for aspect, path in paths.items():
            try:
                report["verified_aspects"][aspect] = verify_video(path, aspect, seconds)
            except (
                IntegrityError,
                subprocess.TimeoutExpired,
                json.JSONDecodeError,
            ) as exc:
                report["errors"][aspect] = str(exc)
    except IntegrityError as exc:
        report["errors"]["preflight"] = str(exc)
    report["status"] = "failed" if report["errors"] else "technical_pass_only"
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        json.dumps(report, ensure_ascii=False, indent=2, allow_nan=False) + "\n"
    )
    print(json.dumps(report, ensure_ascii=False))
    return 1 if report["errors"] else 0


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--seconds", type=float, default=3)
    args = parser.parse_args()
    if not math.isfinite(args.seconds) or args.seconds <= 0:
        parser.error("Expected finite positive duration")
    raise SystemExit(run(args.root, args.report, args.seconds))


if __name__ == "__main__":
    main()
